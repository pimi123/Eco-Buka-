import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'chrome' });
const page = await browser.newPage();
await page.route(/https:\/\/(?:[^/]+\.)?(?:google-analytics\.com|googletagmanager\.com|facebook\.com|facebook\.net)\//, route => route.abort());
const requests = [];
const product = { id: 991, slug: 'seo-test', name: 'SEO Test Battery', price: 249, active: true, in_stock: true, short_description: 'A real product description', category: { name: 'Bateri' } };
await page.route('**/api/**', async route => {
  const url = new URL(route.request().url());
  requests.push(url.pathname);
  if (url.pathname.endsWith('/catalog')) return route.fulfill({ json: { data: [product], total: 48, last_page: 2, facets: null, context: { name: 'Bateri portative', description: 'Bateri portative për shtëpi dhe udhëtime.' } } });
  if (url.pathname.endsWith('/products/seo-test')) return route.fulfill({ json: product });
  if (url.pathname.endsWith('/products/missing')) return route.fulfill({ status: 404, json: {} });
  if (url.pathname.endsWith('/products/broken')) return route.fulfill({ status: 500, json: {} });
  return route.fulfill({ json: [] });
});
try {
  const origin = process.env.TEST_ORIGIN || 'http://127.0.0.1:5174';
  await page.goto(`${origin}/products/seo-test`);
  await page.getByRole('heading', { level: 1, name: product.name }).waitFor();
  await page.getByRole('button', { name: 'Vetëm të domosdoshmet', exact: true }).click();
  assert(requests.some(path => path.endsWith('/products/seo-test')));
  assert(!requests.some(path => path === '/api/products'), 'Detail pages must not fetch the whole catalog');
  assert.match(await page.title(), /SEO Test Battery/);
  const schema = JSON.parse(await page.locator('#page-structured-data').textContent());
  assert.equal(schema['@graph'][0].offers.price, 249);
  assert.equal(schema['@graph'][0].offers.priceCurrency, 'EUR');
  assert.equal(schema['@graph'][0].offers.availability, 'https://schema.org/InStock');
  assert.equal(await page.locator('html').getAttribute('lang'), 'sq');
  assert.match(await page.locator('meta[name="robots"]').getAttribute('content'), /^index/);
  await page.goto(`${origin}/products/missing`);
  await page.getByRole('heading', { name: 'Produkti nuk u gjet' }).waitFor();
  assert.equal(await page.locator('#page-structured-data').count(), 0);
  assert.match(await page.locator('meta[name="robots"]').getAttribute('content'), /^noindex/);
  await page.goto(`${origin}/products/broken`);
  await page.getByRole('button', { name: 'Provo përsëri' }).waitFor();
  assert.equal(await page.locator('h1').count(), 0, 'An API failure must not show a demo product');
  await page.goto(`${origin}/checkout`);
  await page.locator('meta[name="robots"][content="noindex, follow"]').waitFor({ state: 'attached' });
  const mediaRequests = [];
  await page.route('**/*.mp4', route => { mediaRequests.push(route.request().url()); return route.abort(); });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto(`${origin}/solutions/powerocean`, { waitUntil: 'networkidle' });
  assert.equal(mediaRequests.length, 0, 'Mobile must not download background video');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(`${origin}/solutions/powerocean`, { waitUntil: 'networkidle' });
  assert.equal(mediaRequests.length, 0, 'Reduced-motion users must not download background video');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto(`${origin}/solutions/powerocean`, { waitUntil: 'networkidle' });
  assert(mediaRequests.some(url => url.includes('powerocean-hero.mp4')), 'Desktop video should remain available');
  await page.goto(`${origin}/guides/zgjedhja-e-stacionit-te-energjise`);
  await page.getByRole('heading', { level: 1, name: 'Si të zgjidhni një stacion portativ energjie' }).waitFor();
  await page.evaluate(() => document.fonts.ready);
  assert(await page.evaluate(() => document.fonts.check('16px "Eco Helvetica"')), 'The optimized font should load');
  await page.goto(`${origin}/unknown-seo-test`);
  await page.getByRole('heading', { name: 'Faqja nuk u gjet' }).waitFor();
  assert.match(page.url(), /unknown-seo-test$/);
  await page.goto(`${origin}/category/batteries`);
  await page.getByRole('heading', { name: 'Bateri portative', exact: true }).waitFor();
  assert.equal(await page.locator('meta[name="description"]').getAttribute('content'), 'Bateri portative për shtëpi dhe udhëtime.');
  assert.equal(await page.getByRole('link', { name: 'Para', exact: true }).getAttribute('href'), '/category/batteries?page=2');
  await page.getByRole('link', { name: 'Para', exact: true }).click();
  await page.waitForURL('**/category/batteries?page=2');
  await page.waitForFunction(() => document.querySelector('link[rel="canonical"]')?.href.endsWith('?page=2'));
  assert.match(await page.title(), /Faqja 2/);
  await page.goto(`${origin}/category/batteries?stock=1`);
  await page.locator('meta[name="robots"][content="noindex, follow"]').waitFor({ state: 'attached' });
  console.log('PASS: product fetching/schema, metadata, pagination, noindex, 404, API failures, video preferences, guide and fonts.');
} finally {
  await browser.close();
}
